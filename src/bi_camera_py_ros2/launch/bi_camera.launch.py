from launch import LaunchDescription
from launch.actions import DeclareLaunchArgument
from launch.substitutions import LaunchConfiguration, PathJoinSubstitution
from launch_ros.actions import Node
from launch_ros.substitutions import FindPackageShare


def generate_launch_description() -> LaunchDescription:
    config_path = LaunchConfiguration("config_path")

    return LaunchDescription(
        [
            DeclareLaunchArgument(
                "config_path",
                default_value=PathJoinSubstitution([FindPackageShare("bi_camera_py_ros2"), "config", "bi_camera.yaml"]),
                description="Path to the plain YAML config generated by camera_config_wizard.",
            ),
            Node(
                package="bi_camera_py_ros2",
                executable="stereo_camera_node",
                name="bi_camera_publisher",
                output="screen",
                parameters=[{"config_path": config_path}],
            ),
        ]
    )
